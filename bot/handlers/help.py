"""Обработчик помощи"""
from aiogram import Router, types
from aiogram.filters import Command

router = Router()


@router.message(lambda message: message.text == 'Помощь')
@router.message(Command('help'))
async def help_handler(message: types.Message):
    """Обработчик команды помощи"""
    help_text = """
📚 Этот бот поможет тебе подготовиться к ОГЭ и ЕГЭ по русскому языку.

🎯 Как пользоваться:
1. Выбери интересующий вариант экзамена (ОГЭ или ЕГЭ)
2. Выбери номер задания
3. Изучи теорию (PDF файл)
4. Решай задания - после 10 правильных ответов подряд бот предложит пройти тест
5. Пройди тест - нужно набрать минимум 80% правильных ответов

📊 Статистика:
• Следи за своим прогрессом в разделе "Мой профиль"
• Каждая пройденная тема учитывается в статистике

💡 Советы:
• Решай задания регулярно
• Если не получается - вернись к теории
• Проходи тесты для закрепления материала
"""
    await message.answer(text=help_text)


